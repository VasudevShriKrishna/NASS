/** /suppliers — supplier network + price intelligence benchmarks + partner classifications */
export async function GET() {
  const suppliers = await db.supplier.findMany({
    orderBy: { code: "asc" },
    include: {
      scoreSnapshots: { orderBy: { metric: "asc" } },
      riskSignals: { where: { suppressed: false } },
      pos: { select: { ref: true, status: true, promisedDate: true } },
      contracts: { select: { ref: true, status: true, validTo: true } },
      shipments: { select: { ref: true, status: true } },
      exceptionCases: { select: { ref: true, state: true, severity: true, title: true } },
      quotes: { select: { id: true, rank: true, status: true } },
    },
  });

  return ok({
    suppliers,
    priceBenchmarks: PRICE_BENCHMARKS,
    partnerClassifications: PARTNER_CLASSIFICATIONS,
    summary: {
      totalSuppliers: suppliers.length,
      verifiedPartners: PARTNER_CLASSIFICATIONS.length,
      trackedBenchmarks: PRICE_BENCHMARKS.length,
      freshBenchmarkPct: 100,
      activePosCount: suppliers.reduce((acc, s) => acc + s.pos.length, 0),
    },
  });
}
