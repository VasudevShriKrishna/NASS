// Generates src/lib/world-map-paths.ts — SVG path data for every country
// in the 110m world atlas, projected with geoEquirectangular onto a
// 1000 x 420 viewBox (Antarctica trimmed). Run: bun scripts/generate-world-map.mjs
import { readFile, writeFile } from "node:fs/promises";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const W = 1000;
const H = 420;

// Fixed linear equirectangular mapping so client-side marker projection is exact:
//   x = 500 + lng * (500/180)   (lng -180..180 → 0..1000)
//   y = 250 - lat * (500/180)   (lat  90..-90 → 0..500; cropped to 420)
const projection = geoEquirectangular()
  .scale(500 / Math.PI)
  .translate([500, 250])
  .precision(0.2);
const path = geoPath(projection);

const topo = JSON.parse(await readFile("node_modules/world-atlas/countries-110m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features.filter(
  (f) => f.id !== "010" // skip Antarctica — empty southern ocean is cropped away
);

const rows = countries
  .map((f) => ({
    id: String(f.id),
    name: f.properties?.name ?? "",
    d: path(f),
  }))
  .filter((r) => r.d && r.d.length > 0);

const banner = `// AUTO-GENERATED by scripts/generate-world-map.mjs — do not edit by hand.
// Source: world-atlas countries-110m, geoEquirectangular, viewBox 0 0 ${W} ${H}.
// Marker projection (src/lib/geo.ts): x = 500 + lng*(500/180); y = 250 - lat*(500/180).
export interface WorldCountry {
  id: string;
  name: string;
  d: string;
}
export const WORLD_VIEWBOX = { w: ${W}, h: ${H} } as const;
export const WORLD_COUNTRIES: WorldCountry[] = ${JSON.stringify(rows)};
`;

await writeFile("src/lib/world-map-paths.ts", banner, "utf8");
console.log(`world-map-paths.ts written: ${rows.length} countries, ${(banner.length / 1024).toFixed(0)} KB`);
